const dictionaries: Record<Language, Record<string, string>> = {
  zh: zh as unknown as Record<string, string>,
  en: en as Record<string, string>,
};

export type TranslateParams = Record<string, string | number>;

function interpolate(template: string, params?: TranslateParams): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

export function translate(language: Language, key: string, params?: TranslateParams): string {
  return interpolate(dictionaries[language][key] ?? dictionaries.zh[key] ?? key, params);
}

/** English singular form: prefer `<key>.one` when count === 1. */
export function translateCount(
  language: Language,
  key: string,
  count: number,
  params?: TranslateParams,
): string {
  const dictionary = dictionaries[language];
  const base = language === 'en' && count === 1 ? `${key}.one` : key;
  const template = dictionary[base] ?? dictionary[key] ?? dictionaries.zh[key] ?? key;
  return interpolate(template, { count, ...params });
}

export function currentLanguage(): Language {
  return useUiStore.getState().language;
}

/** Non-hook translation for modules outside React render. */
export function t(key: string, params?: TranslateParams): string {
  return translate(currentLanguage(), key, params);
}

export function useI18n() {
  const language = useUiStore((state) => state.language);
  const t = useCallback(
    (key: string, params?: TranslateParams) => translate(language, key, params),
    [language],
  );
  const tn = useCallback(
    (key: string, count: number, params?: TranslateParams) =>
      translateCount(language, key, count, { count, ...params }),
    [language],
  );

  return { language, t, tn };
}
